"""Build the results/ folder of this repository from the FINAL per-family packages.

Rules (enforced in code):
  1. A family is released only if every *data* check in verify_release.py passes.
  2. A family's original run manifest is released only if its *metadata* checks also pass.
  3. Nothing containing model-generated text is released: raw generations, audit sheets and the
     combined judged files are NOT copied. Row-level judged tables are released as *label-only*
     files (prompt_text / response_text / judge_notes / human_notes columns removed), which is all
     that the statistics and figures need. Benign prompts and the harmful base prompts live in data/prompts/.

Usage:
    PACKAGES_ROOT=/path/to/unzipped/final/packages python common/build_results_release.py
"""
import argparse, glob, hashlib, json, os, re, shutil, sys
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
import verify_release as V

OUT = os.path.join(os.path.dirname(__file__), "..", "results")
TEXT_COLS = re.compile(r"text|response|notes|rationale", re.I)

TABLES = ["summary_by_model_precision_attack.csv", "benign_summary.csv", "benign_paired_stats.csv", "stats_tests.csv",
          "safety_tax_deltas.csv", "blocked_row_sensitivity.csv", "sensitivity_excl_blocked_rows.csv", "leakage_deltas.csv",
          "audit_agreement.csv", "audit_confusion_matrices.csv", "human_corrected_metric_summary.csv",
          "human_corrected_stats_tests.csv", "human_corrected_safety_tax_deltas.csv", "generation_run_provenance.csv",
          "preflight_summary.json", "JUDGE_EXECUTION_NOTE.json",
          "audit/human_audit_agreement.csv", "audit/human_audit_disagreements.csv", "audit/human_audit_summary.json",
          "VALIDATION_REPORT.json"]
DOC_GLOBS = ["*CLAIM_CHECK*.md", "VALIDATION_REPORT*.md", "README_*_FINAL.md", "audit_provenance.md", "AUDIT_SUBSET_NOTE.md"]
# label-only row-level files: (source name, release name)
ROWLEVEL = lambda fam: [(f"judged_harmful_{fam}_all.csv", f"judged_harmful_{fam}_labels.csv"),
                        (f"judged_benign_{fam}_all.csv", f"judged_benign_{fam}_labels.csv")]
EXTRA_ROWLEVEL = {"smollm": [("human_corrected_harmful_population.csv", "human_corrected_harmful_population_labels.csv")],
                  "granite": [("human_corrected_granite_all.csv", "human_corrected_harmful_population_labels.csv")]}


def strip_text(src, dst):
    d = pd.read_csv(src, low_memory=False)
    keep = [c for c in d.columns if not TEXT_COLS.search(c)]
    assert any(c.startswith("judge_") for c in keep), f"{src}: stripped too much"
    d[keep].to_csv(dst, index=False)
    return len(d), len(d.columns) - len(keep)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--include-all", action="store_true", help="release every family and manifest as-is, even if a check failed (failures stay listed in VERIFICATION_REPORT.md)")
    args = ap.parse_args()
    root = os.environ.get("PACKAGES_ROOT", "./packages")
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    verdicts, report = {}, ["# Verification report for the final per-family packages", "",
                            "Generated by `common/verify_release.py` (called from `common/build_results_release.py`). 'data' checks gate the release of a "
                            "family's tables; 'metadata' checks (manifest hashes/status) gate only whether its original run manifest is released.", ""]
    for fam, (rel, _) in V.PACKAGES.items():
        P = os.path.join(root, rel); top = os.path.join(root, V.PKG_TOP.get(fam, rel))
        try:
            res = V.verify(fam, root)
        except Exception as e:
            res = [("verification_crashed", False, repr(e))]
        meta = lambda n: n.startswith("manifest_")
        data_ok = all(p for n, p, _ in res if not meta(n)); meta_ok = all(p for n, p, _ in res if meta(n))
        if args.include_all:
            data_ok, meta_ok = True, True
            label = "RELEASED AS-IS" + ("" if all(p for _, p, _ in res) else " (some checks failed, see below)")
        else:
          label = "VERIFIED" if data_ok and meta_ok else ("DATA VERIFIED, manifest withheld (metadata issue)" if data_ok else "NOT VERIFIED - NOT RELEASED")
        verdicts[fam] = (data_ok, meta_ok)
        report += [f"## {fam}: {label}", "", "| check | kind | result | detail |", "|---|---|---|---|"]
        report += [f"| {n} | {'metadata' if meta(n) else 'data'} | {'pass' if p else '**FAIL**'} | {d[:170]} |" for n, p, d in res] + [""]
        print(f"{fam:8} {label}")
        if not data_ok:
            continue
        dst = os.path.join(OUT, fam); os.makedirs(dst)
        copied = []
        for t in TABLES:
            for base in (top, P):
                s = os.path.join(base, t)
                if os.path.isfile(s):
                    shutil.copy(s, os.path.join(dst, os.path.basename(t))); copied.append(os.path.basename(t)); break
        for g in DOC_GLOBS:
            for base in dict.fromkeys((top, P)):
                for s in glob.glob(os.path.join(base, g)):
                    shutil.copy(s, os.path.join(dst, os.path.basename(s))); copied.append(os.path.basename(s))
        if fam == "qwen":
            for s in glob.glob(os.path.join(top, "paper_tables", "*.csv")):
                shutil.copy(s, os.path.join(dst, "paper_" + os.path.basename(s))); copied.append("paper_" + os.path.basename(s))
        for s_name, d_name in ROWLEVEL(fam) + EXTRA_ROWLEVEL.get(fam, []):
            s = next((os.path.join(b, s_name) for b in (P, top) if os.path.isfile(os.path.join(b, s_name))), None)
            if s:
                n, dropped = strip_text(s, os.path.join(dst, d_name)); copied.append(f"{d_name} ({n} rows, {dropped} text columns removed)")
        if meta_ok:   # canonical manifest only
            mf = sorted([f for f in os.listdir(top) if f.startswith("run_manifest") and f.endswith(".json")], key=lambda x: ("final" not in x, x))
            canon = None
            for f in mf:
                if V.find_hashmap(json.load(open(os.path.join(top, f)))):
                    canon = f; break
            if canon:
                shutil.copy(os.path.join(top, canon), os.path.join(dst, canon)); copied.append(canon)
        else:
            report += [f"> **{fam}: original run manifest withheld** because a metadata check failed (see table above); the verified tables are released.", ""]
        print("   ", len(copied), "files")
    open(os.path.join(OUT, "VERIFICATION_REPORT.md"), "w").write("\n".join(report) + "\n")
    # checksums for integrity of the released files
    lines = []
    for p in sorted(glob.glob(os.path.join(OUT, "**", "*"), recursive=True)):
        if os.path.isfile(p) and not p.endswith("SHA256SUMS"):
            lines.append(f"{hashlib.sha256(open(p, 'rb').read()).hexdigest()}  {os.path.relpath(p, OUT)}")
    open(os.path.join(OUT, "SHA256SUMS"), "w").write("\n".join(lines) + "\n")
    not_released = [f for f, (d, _) in verdicts.items() if not d]
    print("not released (failed data checks):", not_released or "none")
    sys.exit(1 if not_released else 0)


if __name__ == "__main__":
    main()
